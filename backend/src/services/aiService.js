/**
 * AI Assistant Service for Task Management
 * Supports OpenAI-compatible LLM endpoints (Groq / OpenAI) & Google Gemini API
 * Includes resilient timeouts and automatic heuristic fallback for graceful failure handling.
 */

// Heuristic fallback for offline, network timeout, or quota exhaustion
const generateFallbackAnalysis = (taskTitle) => {
  const lower = (taskTitle || "").toLowerCase();

  let priority = "Medium";
  let estimatedDays = 3;
  let deadlineText = "In 3 days";

  if (/\b(urgent|critical|security|bug|fix|crash|down|hotfix|asap|leak|immediately)\b/.test(lower)) {
    priority = "High";
    estimatedDays = 1;
    deadlineText = "Within 24 hours";
  } else if (/\b(read|buy|watch|clean|organize|someday|idea|wishlist|explore|learn)\b/.test(lower)) {
    priority = "Low";
    estimatedDays = 7;
    deadlineText = "In 1 week";
  }

  const subtasks = [
    `Clarify requirements and scope for "${taskTitle}"`,
    `Execute core implementation steps`,
    `Review, verify outcomes, and mark as completed`,
  ];

  return {
    title: taskTitle,
    description: `Focus on executing: "${taskTitle}". Plan the necessary resources and verify each step thoroughly.`,
    priority,
    suggestedDeadline: deadlineText,
    estimatedDays,
    reasoning: `Categorized as ${priority} priority based on keyword semantics and estimated effort.`,
    suggestedSubtasks: subtasks,
    provider: "Smart Heuristic Analyzer (Fallback)",
    aiGenerated: true,
  };
};

/**
 * Call Groq / OpenAI-compatible endpoint
 */
const callGroqAPI = async (taskTitle, apiKey) => {
  const model = process.env.AI_MODEL || "openai/gpt-oss-120b";
  const url = "https://api.groq.com/openai/v1/chat/completions";

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 8000);

  try {
    const response = await fetch(url, {
      method: "POST",
      headers: {
        "Authorization": `Bearer ${apiKey}`,
        "Content-Type": "application/json",
      },
      signal: controller.signal,
      body: JSON.stringify({
        model,
        messages: [
          {
            role: "system",
            content:
              "You are an expert agile task planning assistant. Return a JSON object with: " +
              "\"description\" (clear 1-2 sentence overview), " +
              "\"priority\" (strictly 'Low', 'Medium', or 'High'), " +
              "\"suggestedDeadline\" (string like 'In 2 days', 'Within 24 hours', 'In 1 week'), " +
              "\"estimatedDays\" (integer number of days), " +
              "\"reasoning\" (1 concise sentence explaining the priority), " +
              "\"suggestedSubtasks\" (array of 3-5 concise, actionable strings). Output valid JSON only.",
          },
          {
            role: "user",
            content: `Analyze this task title: "${taskTitle}"`,
          },
        ],
        response_format: { type: "json_object" },
        temperature: 0.3,
      }),
    });

    clearTimeout(timeoutId);

    if (!response.ok) {
      const errText = await response.text();
      throw new Error(`Groq API responded with HTTP ${response.status}: ${errText.slice(0, 150)}`);
    }

    const data = await response.json();
    const rawContent = data.choices?.[0]?.message?.content;
    const parsed = typeof rawContent === "string" ? JSON.parse(rawContent) : rawContent;

    return {
      title: taskTitle,
      description: parsed.description || `Execute: ${taskTitle}`,
      priority: ["Low", "Medium", "High"].includes(parsed.priority) ? parsed.priority : "Medium",
      suggestedDeadline: parsed.suggestedDeadline || `${parsed.estimatedDays || 3} days`,
      estimatedDays: parsed.estimatedDays || 3,
      reasoning: parsed.reasoning || "Generated by AI task planning model.",
      suggestedSubtasks: Array.isArray(parsed.suggestedSubtasks) ? parsed.suggestedSubtasks : [],
      provider: `Groq (${model})`,
      aiGenerated: true,
    };
  } finally {
    clearTimeout(timeoutId);
  }
};

/**
 * Call Google Gemini endpoint
 */
const callGeminiAPI = async (taskTitle, apiKey) => {
  const model = "gemini-3.8-flash";
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 8000);

  try {
    const prompt =
      `Analyze the task title "${taskTitle}" and output valid JSON with: ` +
      `"description" (string), "priority" ("Low" | "Medium" | "High"), "suggestedDeadline" (string), ` +
      `"estimatedDays" (number), "reasoning" (string), "suggestedSubtasks" (array of 3-5 strings). Return JSON only.`;

    const response = await fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      signal: controller.signal,
      body: JSON.stringify({
        contents: [{ parts: [{ text: prompt }] }],
      }),
    });

    clearTimeout(timeoutId);

    if (!response.ok) {
      const errText = await response.text();
      throw new Error(`Gemini API HTTP ${response.status}: ${errText.slice(0, 150)}`);
    }

    const data = await response.json();
    let text = data.candidates?.[0]?.content?.parts?.[0]?.text || "{}";
    // Strip markdown code block wrappers if any
    text = text.replace(/```json/g, "").replace(/```/g, "").trim();
    const parsed = JSON.parse(text);

    return {
      title: taskTitle,
      description: parsed.description || `Execute: ${taskTitle}`,
      priority: ["Low", "Medium", "High"].includes(parsed.priority) ? parsed.priority : "Medium",
      suggestedDeadline: parsed.suggestedDeadline || `${parsed.estimatedDays || 3} days`,
      estimatedDays: parsed.estimatedDays || 3,
      reasoning: parsed.reasoning || "Generated by Gemini AI model.",
      suggestedSubtasks: Array.isArray(parsed.suggestedSubtasks) ? parsed.suggestedSubtasks : [],
      provider: `Google Gemini (${model})`,
      aiGenerated: true,
    };
  } finally {
    clearTimeout(timeoutId);
  }
};

/**
 * Main AI Task Enhancement Entrypoint
 * Handles primary LLM calls, fallbacks, and error boundaries.
 */
const enhanceTask = async (taskTitle) => {
  const title = (taskTitle || "").trim();
  if (!title) {
    throw new Error("Task title is required for AI enhancement.");
  }

  const groqKey = process.env.GROQ_API_KEY;
  const geminiKey = process.env.GEMINI_API_KEY;

  // 1. Try Groq (OpenAI-compatible) first if configured
  if (groqKey && groqKey.startsWith("gsk_")) {
    try {
      return await callGroqAPI(title, groqKey);
    } catch (err) {
      console.warn("⚠️ Groq AI attempt failed, attempting fallback:", err.message);
    }
  }

  // 2. Try Gemini if configured
  if (geminiKey) {
    try {
      return await callGeminiAPI(title, geminiKey);
    } catch (err) {
      console.warn("⚠️ Gemini AI attempt failed, engaging heuristic analyzer:", err.message);
    }
  }

  // 3. Fallback: Always return a high-quality structured response so the app never fails
  return generateFallbackAnalysis(title);
};

module.exports = {
  enhanceTask,
  generateFallbackAnalysis,
};
